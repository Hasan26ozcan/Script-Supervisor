def _persist_run(metrics: dict[str, Any], chart_paths: dict[str, Path]) -> dict[str, Any]:
    """Write one evaluation-run row to the SQL backend and read it back,
    so the reported `database_backend` reflects what actually happened
    rather than an assumed string."""
    from app.db import Base, EvaluationRunModel, create_sessionmaker

    try:
        session_local, engine = create_sessionmaker()
        dialect_name = engine.dialect.name
    except Exception:  # pragma: no cover - offline environments lack DB drivers
        return {
            "attempted_backend": "unavailable",
            "persisted": False,
            "row_count_after_write": None,
            "error": "database backend unavailable",
        }
    persisted = False
    error: str | None = None
    row_count: int | None = None
    try:
        Base.metadata.create_all(bind=engine)
        session = session_local()
        try:
            row = EvaluationRunModel(
                run_id=f"run_{datetime.now(UTC).strftime('%Y%m%dT%H%M%S%f')}",
                created_at=datetime.now(UTC).isoformat(),
                suite_name=metrics["suite_name"],
                dataset_name=metrics["dataset_name"],
                n_samples=metrics["n_samples"],
                holdout_size=metrics["holdout_size"],
                accuracy=metrics["win_rate"],
                report_markdown_path=str(metrics.get("_markdown_path", "")),
                report_html_path=str(metrics.get("_html_path", "")),
                metrics_json_path=str(metrics.get("_metrics_path", "")),
                charts_json=json.dumps({k: str(v) for k, v in chart_paths.items()}),
            )
            session.add(row)
            session.commit()
            persisted = True
            row_count = session.query(EvaluationRunModel).count()
        finally:
            session.close()
    except Exception as exc:  # pragma: no cover - exercised when DB is unreachable
        error = str(exc)

    return {
        "attempted_backend": dialect_name,
        "persisted": persisted,
        "row_count_after_write": row_count,
        "error": error,
    }


def _summarize_preferences(preferences: list[PreferencePair]) -> dict[str, Any]:
    winner_counts = Counter(pref.winner for pref in preferences)
    rater_counts = Counter(pref.rater for pref in preferences)
    return {
        "n_samples": len(preferences),
        "winner_counts": dict(winner_counts),
        "rater_counts": dict(rater_counts),
    }


def run_evaluation_suite(
    preferences: list[PreferencePair],
    workspace_root: Path | None = None,
    suite_name: str = "default-suite",
    include_demo_dataset: bool = True,
) -> dict[str, Any]:
    if not preferences:
        raise SystemExit(
            "No preferences found. Run `python -m training.generate_fake_preferences` first."
        )
    paths = _ensure_output_dirs(workspace_root)
    charts_dir = paths["charts"]

    summary = _summarize_preferences(preferences)
    demo_dataset_included = include_demo_dataset and summary["n_samples"] >= 20

    non_tie = [p for p in preferences if p.winner != "tie"]
    a_win_outcomes = [1 if p.winner == "a" else 0 for p in non_tie]
    win_point, win_lo, win_hi = _bootstrap_win_rate_ci(a_win_outcomes)
    significance = _binomial_significance(sum(a_win_outcomes), len(a_win_outcomes))
    bradley_terry = _fit_bradley_terry(a_win_outcomes)

    judge_predictions = [_heuristic_judge_winner(p) for p in preferences]
    human_labels = [p.winner for p in preferences]
    agreement_rate = round(
        sum(1 for j, h in zip(judge_predictions, human_labels, strict=True) if j == h)
        / max(1, len(preferences)),
        4,
    )
    kappa = _cohens_kappa(judge_predictions, human_labels)

    single_rating_per_item = len(set(summary["rater_counts"].keys())) == summary["n_samples"]

    chart_paths: dict[str, Path] = {}

    chart_paths["win_rate_ci"] = _safe_path_join(charts_dir, "win_rate_ci.png")
    _write_win_rate_ci_chart(chart_paths["win_rate_ci"], win_point, win_lo, win_hi)

    cumulative = (
        list(np.cumsum(a_win_outcomes) / np.arange(1, len(a_win_outcomes) + 1))
        if a_win_outcomes
        else []
    )
    chart_paths["win_rate_trend"] = _safe_path_join(charts_dir, "win_rate_trend.png")
    _write_trend_chart(
        chart_paths["win_rate_trend"],
        "Cumulative A win rate over chronological samples",
        cumulative,
        "Cumulative win rate",
    )

    rater_labels = list(summary["rater_counts"].keys())
    rater_values = [summary["rater_counts"][r] for r in rater_labels]
    chart_paths["samples_per_rater"] = _safe_path_join(charts_dir, "samples_per_rater.png")
    _write_bar_chart(
        chart_paths["samples_per_rater"],
        "Samples per rater",
        rater_labels,
        rater_values,
        "Judgments",
    )

    metrics: dict[str, Any] = {
        "suite_name": suite_name,
        "dataset_name": "fake_human_judgments_20_samples",
        "n_samples": summary["n_samples"],
        "holdout_size": max(1, int(round(summary["n_samples"] * 0.2))),
        "demo_dataset_included": demo_dataset_included,
        "win_rate": round(win_point, 4),
        "win_rate_95ci": [round(win_lo, 4), round(win_hi, 4)],
        "significance_vs_50_50": significance,
        "bradley_terry": bradley_terry,
        "heuristic_judge_agreement_rate": agreement_rate,
        "heuristic_judge_cohens_kappa": kappa,
        "inter_rater_reliability": (
            "not computable: every item in this dataset has exactly one rater"
            if single_rating_per_item
            else "computed"
        ),
        "preferences_by_winner": summary["winner_counts"],
        "preferences_by_rater": summary["rater_counts"],
        "reporting_format": ["markdown", "html", "json"],
        "limitations": [
            "Demo dataset uses only two fixed candidate templates repeated across all "
            "20 briefs, so the Bradley-Terry strength gap reflects template style, "
            "not per-brief quality.",
            "One rater per item: no real inter-rater reliability (kappa) is possible "
            "on this dataset; collect >=2 raters/item for that.",
            "heuristic_judge_* metrics come from a deterministic offline text-feature "
            "judge, not a live LLM-graded judge -- see module docstring.",
        ],
    }

    persistence = _persist_run(metrics, chart_paths)
    metrics["database_backend"] = persistence["attempted_backend"]
    metrics["database_write_persisted"] = persistence["persisted"]
    metrics["database_row_count_after_write"] = persistence["row_count_after_write"]
    if persistence["error"]:
        metrics["database_error"] = persistence["error"]

    ci_range = f"{metrics['win_rate_95ci'][0]:.3f}-{metrics['win_rate_95ci'][1]:.3f}"
    significance_line = (
        f"p = {significance.get('p_value')}, "
        f"significant at 0.05: {significance.get('significant_at_05')}"
    )
    database_line = (
        f"Database backend actually used: {metrics['database_backend']} "
        f"(write persisted: {metrics['database_write_persisted']})"
    )

    markdown = f"""# Evaluation Report

- Suite: {suite_name}
- Dataset: {metrics["dataset_name"]} (demo dataset included: {demo_dataset_included})
- Samples: {metrics["n_samples"]} (holdout size used for reporting: {metrics["holdout_size"]})
- Candidate A win rate: {metrics["win_rate"]:.3f} (95% bootstrap CI: {ci_range})
- Two-sided binomial test vs 50/50: {significance_line}
- Bradley-Terry P(A beats B): {bradley_terry.get("p_a_beats_b")}
- Heuristic judge vs human agreement: {agreement_rate:.3f} (Cohen's kappa: {kappa})
- Inter-rater reliability: {metrics["inter_rater_reliability"]}
- {database_line}

## Limitations (read before citing these numbers)
{chr(10).join("- " + item for item in metrics["limitations"])}

## Summary
This report is generated by a statistically grounded pipeline: bootstrap
confidence intervals, a binomial significance test, a Bradley-Terry MLE
fit, and an automated-judge-vs-human agreement check (with Cohen's kappa).
It is intentionally conservative about what the bundled 20-sample demo
dataset can and cannot support -- see the limitations above.
"""
    html_ci_range = f"{metrics['win_rate_95ci'][0]:.3f}-{metrics['win_rate_95ci'][1]:.3f}"
    html_database_line = (
        f"Database backend: {metrics['database_backend']} "
        f"(persisted: {metrics['database_write_persisted']})"
    )

    html = f"""<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>{suite_name} report</title></head>
<body>
<h1>Evaluation Report</h1>
<p>Suite: {suite_name}</p>
<p>Samples: {metrics["n_samples"]}</p>
<p>Candidate A win rate: {metrics["win_rate"]:.3f} (95% CI {html_ci_range})</p>
<p>Binomial test p-value: {significance.get("p_value")}</p>
<p>Bradley-Terry P(A beats B): {bradley_terry.get("p_a_beats_b")}</p>
<p>Heuristic judge agreement: {agreement_rate:.3f} (kappa: {kappa})</p>
<p>{html_database_line}</p>
<h2>Limitations</h2>
<ul>
{"".join(f"<li>{item}</li>" for item in metrics["limitations"])}
</ul>
</body>
</html>
"""

    # Re-derive and re-validate the destination paths immediately before the
    # writes, from the already-sandboxed reports directory plus fixed,
    # hardcoded filenames only -- never from external/config-provided data at
    # this point -- so each sink is provably safe on its own.
    reports_dir = paths["reports_dir"]
    safe_markdown_path = _safe_path_join(reports_dir, "evaluation_report.md")
    safe_html_path = _safe_path_join(reports_dir, "evaluation_report.html")
    safe_metrics_path = _safe_path_join(reports_dir, "metrics.json")
    safe_markdown_path.write_text(markdown, encoding="utf-8")
    safe_html_path.write_text(html, encoding="utf-8")
    safe_metrics_path.write_text(json.dumps(metrics, indent=2), encoding="utf-8")

    return {
        "summary": summary,
        "metrics": metrics,
        "report_markdown_path": paths["markdown"],
        "report_html_path": paths["html"],
        "metrics_json_path": paths["metrics"],
        "chart_paths": chart_paths,
    }


if __name__ == "__main__":
    with PreferenceStore() as store:
        prefs = store.all()
    if not prefs:
        raise SystemExit(
            "No preferences found. Run `python -m training.generate_fake_preferences` first."
        )
    result = run_evaluation_suite(prefs, suite_name="cli-run")
    print(json.dumps(result["metrics"], indent=2))
