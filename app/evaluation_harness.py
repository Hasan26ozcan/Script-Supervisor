"""Evaluation harness for the Creative Harness.

Honesty note (read before trusting any number this module prints):
the bundled demonstration dataset (`data/preferences.jsonl`, 20 rows) uses
exactly two fixed candidate templates and one rater per item, generated by
`training.generate_fake_preferences`. That means:

- There is no way to compute real inter-rater reliability (Cohen's/Fleiss'
  kappa) from it, because no item has more than one rating. This module
  says so explicitly in its output rather than fabricating a kappa value.
- The "judge" scorer below is a deterministic *heuristic* stand-in
  (keyword/length features), not a real LLM-graded judge. It exists so the
  agreement-with-automated-judge metric has something real to compute in
  mock/offline mode. Swap it for `app.rubric.Rubric` + a live model call
  when `HARNESS_MOCK_MODE=0` and real preference data is collected with
  >=2 raters per item.

What this module *does* do honestly, using real statistics (numpy/scipy):

1. Bootstrap confidence interval on the human win rate (percentile method).
2. A two-sided binomial test of the win rate against a 50/50 null.
3. A maximum-likelihood Bradley-Terry fit of relative candidate-template
   strength from the pairwise outcomes.
4. Agreement rate + Cohen's kappa between the heuristic judge and the
   recorded human winner (a real "model-graded vs human" check, the
   standard pattern used by modern LLM eval harnesses -- see
   docs/evaluation/HARNESS_NOTES.md for the industry references this is
   modeled on).
5. Persists one row per run to the SQL backend (Postgres in production,
   file-based SQLite fallback offline) via SQLAlchemy, and reads it back
   to report which backend actually served the write -- not a hardcoded
   string.
"""
from __future__ import annotations

import json
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy import stats as scipy_stats
from scipy.optimize import minimize

from app.config import settings
from app.schemas import PreferencePair

BOOTSTRAP_RESAMPLES = 5000
RNG_SEED = 20260726  # fixed for reproducible reports


def _ensure_output_dirs(workspace_root: Path | None = None) -> dict[str, Path]:
    root = workspace_root or Path.cwd()
    reports_dir = root / settings.evaluation_reports_dir
    charts_dir = reports_dir / "charts"
    reports_dir.mkdir(parents=True, exist_ok=True)
    charts_dir.mkdir(parents=True, exist_ok=True)
    return {
        "root": root,
        "reports_dir": reports_dir,
        "markdown": reports_dir / "evaluation_report.md",
        "html": reports_dir / "evaluation_report.html",
        "metrics": reports_dir / "metrics.json",
        "charts": charts_dir,
    }


def _bootstrap_win_rate_ci(
    outcomes: list[int], n_resamples: int = BOOTSTRAP_RESAMPLES, confidence: float = 0.95
) -> tuple[float, float, float]:
    """Percentile-bootstrap CI on the mean of a 0/1 outcome vector."""
    arr = np.asarray(outcomes, dtype=float)
    if arr.size == 0:
        return 0.0, 0.0, 0.0
    point = float(arr.mean())
    rng = np.random.default_rng(RNG_SEED)
    idx = rng.integers(0, arr.size, size=(n_resamples, arr.size))
    resample_means = arr[idx].mean(axis=1)
    alpha = 1 - confidence
    lower = float(np.percentile(resample_means, 100 * (alpha / 2)))
    upper = float(np.percentile(resample_means, 100 * (1 - alpha / 2)))
    return point, lower, upper


def _binomial_significance(n_success: int, n_total: int) -> dict[str, Any]:
    if n_total == 0:
        return {"p_value": None, "significant_at_05": False, "null_hypothesis": "win_rate == 0.5"}
    result = scipy_stats.binomtest(n_success, n_total, p=0.5, alternative="two-sided")
    return {
        "p_value": round(float(result.pvalue), 4),
        "significant_at_05": bool(result.pvalue < 0.05),
        "null_hypothesis": "win_rate == 0.5",
    }


def _fit_bradley_terry(pairwise_a_wins: list[int]) -> dict[str, Any]:
    """MLE fit of a two-parameter Bradley-Terry model (template_a vs
    template_b strength). Reports the strength gap and its rough standard
    error from the inverse Hessian of the negative log-likelihood."""
    wins_a = sum(pairwise_a_wins)
    n = len(pairwise_a_wins)
    if n == 0:
        return {"strength_gap_logit": 0.0, "std_error": None, "p_a_beats_b": 0.5}

    def neg_log_likelihood(theta: np.ndarray) -> float:
        # theta[0] = strength of A minus strength of B (log-odds scale)
        gap = theta[0]
        p_a = 1 / (1 + np.exp(-gap))
        p_a = min(max(p_a, 1e-9), 1 - 1e-9)
        return -(wins_a * np.log(p_a) + (n - wins_a) * np.log(1 - p_a))

    fit = minimize(neg_log_likelihood, x0=np.array([0.0]), method="BFGS")
    gap = float(fit.x[0])
    std_error = None
    if fit.hess_inv is not None:
        try:
            std_error = float(
                np.sqrt(np.asarray(fit.hess_inv).reshape(1, 1)[0, 0])
            )
        except Exception:  # pragma: no cover - defensive against solver edge cases
            std_error = None
    p_a = float(1 / (1 + np.exp(-gap)))
    return {
        "strength_gap_logit": round(gap, 4),
        "std_error": std_error,
        "p_a_beats_b": round(p_a, 4),
    }


def _heuristic_judge_winner(pref: PreferencePair) -> str:
    """Deterministic, offline stand-in for a real LLM judge. Scores each
    candidate on two cheap textual proxies for the rubric criteria this
    project already tracks (`app/rubric.py`: clarity, tone_match,
    actionability) -- sentence count as a clarity/structure proxy and
    presence of concrete camera/action verbs as an actionability proxy.
    This is intentionally simple and is NOT a substitute for a real
    model-graded judge; see module docstring."""
    action_words = ("cut", "reveal", "establish", "emphasize", "keep", "introduce")

    def score(text: str) -> float:
        sentences = max(1, text.count(".") + text.count("\n"))
        action_hits = sum(text.lower().count(w) for w in action_words)
        return sentences + 0.5 * action_hits

    score_a = score(pref.candidate_a)
    score_b = score(pref.candidate_b)
    if abs(score_a - score_b) < 1e-9:
        return "tie"
    return "a" if score_a > score_b else "b"


def _cohens_kappa(labels_x: list[str], labels_y: list[str]) -> float | None:
    if not labels_x or len(labels_x) != len(labels_y):
        return None
    categories = sorted(set(labels_x) | set(labels_y))
    if len(categories) < 2:
        return None
    n = len(labels_x)
    observed_agreement = sum(
        1 for x, y in zip(labels_x, labels_y, strict=True) if x == y
    ) / n
    px = {c: labels_x.count(c) / n for c in categories}
    py = {c: labels_y.count(c) / n for c in categories}
    expected_agreement = sum(px[c] * py[c] for c in categories)
    if expected_agreement >= 1.0:
        return 1.0
    return round((observed_agreement - expected_agreement) / (1 - expected_agreement), 4)


def _write_win_rate_ci_chart(path: Path, point: float, lower: float, upper: float) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(7, 4.5))
    plt.bar(
        ["A win rate"],
        [point],
        yerr=[[max(0.0, point - lower)], [max(0.0, upper - point)]],
        capsize=6,
        color="#4f46e5",
    )
    plt.axhline(0.5, color="#9ca3af", linestyle="--", linewidth=1, label="50% baseline")
    plt.ylim(0, 1)
    plt.title("Candidate A win rate (95% bootstrap CI)")
    plt.ylabel("Win rate")
    plt.legend()
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def _write_trend_chart(path: Path, title: str, y_values: list[float], ylabel: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(7, 4.5))
    x_values = list(range(1, len(y_values) + 1))
    plt.plot(x_values, y_values, marker="o", color="#0ea5e9")
    plt.axhline(0.5, color="#9ca3af", linestyle="--", linewidth=1, label="50% baseline")
    plt.title(title)
    plt.xlabel("Sample index (chronological)")
    plt.ylabel(ylabel)
    plt.ylim(0, 1)
    plt.legend()
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def _write_bar_chart(path: Path, title: str, labels: list[str], values: list[float], ylabel: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    plt.figure(figsize=(7, 4.5))
    plt.bar(labels, values, color="#22c55e")
    plt.title(title)
    plt.ylabel(ylabel)
    plt.xticks(rotation=30, ha="right")
    plt.tight_layout()
    plt.savefig(path, dpi=180)
    plt.close()


def _persist_run(metrics: dict[str, Any], chart_paths: dict[str, Path]) -> dict[str, Any]:
    """Write one evaluation-run row to the SQL backend and read it back,
    so the reported `database_backend` reflects what actually happened
    rather than an assumed string."""
    from app.db import Base, EvaluationRunModel, create_sessionmaker

    session_local, engine = create_sessionmaker()
    dialect_name = engine.dialect.name
    persisted = False
    error: str | None = None
    row_count: int | None = None
    try:
        Base.metadata.create_all(bind=engine)
        session = session_local()
        try:
            row = EvaluationRunModel(
                run_id=f"run_{datetime.now(UTC).strftime('%Y%m%dT%H%M%S%f')}",
                created_at=datetime.now(UTC).isoformat(),
                suite_name=metrics["suite_name"],
                dataset_name=metrics["dataset_name"],
                n_samples=metrics["n_samples"],
                holdout_size=metrics["holdout_size"],
                accuracy=metrics["win_rate"],
                report_markdown_path=str(metrics.get("_markdown_path", "")),
                report_html_path=str(metrics.get("_html_path", "")),
                metrics_json_path=str(metrics.get("_metrics_path", "")),
                charts_json=json.dumps({k: str(v) for k, v in chart_paths.items()}),
            )
            session.add(row)
            session.commit()
            persisted = True
            row_count = session.query(EvaluationRunModel).count()
        finally:
            session.close()
    except Exception as exc:  # pragma: no cover - exercised when DB is unreachable
        error = str(exc)

    return {
        "attempted_backend": dialect_name,
        "persisted": persisted,
        "row_count_after_write": row_count,
        "error": error,
    }


def _summarize_preferences(preferences: list[PreferencePair]) -> dict[str, Any]:
    winner_counts = Counter(pref.winner for pref in preferences)
    rater_counts = Counter(pref.rater for pref in preferences)
    return {
        "n_samples": len(preferences),
        "winner_counts": dict(winner_counts),
        "rater_counts": dict(rater_counts),
    }


def run_evaluation_suite(
    preferences: list[PreferencePair],
    workspace_root: Path | None = None,
    suite_name: str = "default-suite",
    include_demo_dataset: bool = True,
) -> dict[str, Any]:
    paths = _ensure_output_dirs(workspace_root)
    charts_dir = paths["charts"]

    summary = _summarize_preferences(preferences)
    demo_dataset_included = include_demo_dataset and summary["n_samples"] >= 20

    non_tie = [p for p in preferences if p.winner != "tie"]
    a_win_outcomes = [1 if p.winner == "a" else 0 for p in non_tie]
    win_point, win_lo, win_hi = _bootstrap_win_rate_ci(a_win_outcomes)
    significance = _binomial_significance(sum(a_win_outcomes), len(a_win_outcomes))
    bradley_terry = _fit_bradley_terry(a_win_outcomes)

    judge_predictions = [_heuristic_judge_winner(p) for p in preferences]
    human_labels = [p.winner for p in preferences]
    agreement_rate = round(
        sum(1 for j, h in zip(judge_predictions, human_labels, strict=True) if j == h)
        / max(1, len(preferences)),
        4,
    )
    kappa = _cohens_kappa(judge_predictions, human_labels)

    single_rating_per_item = len(set(summary["rater_counts"].keys())) == summary["n_samples"]

    chart_paths: dict[str, Path] = {}

    chart_paths["win_rate_ci"] = charts_dir / "win_rate_ci.png"
    _write_win_rate_ci_chart(chart_paths["win_rate_ci"], win_point, win_lo, win_hi)

    cumulative = (
        list(np.cumsum(a_win_outcomes) / np.arange(1, len(a_win_outcomes) + 1)) if a_win_outcomes else []
    )
    chart_paths["win_rate_trend"] = charts_dir / "win_rate_trend.png"
    _write_trend_chart(
        chart_paths["win_rate_trend"],
        "Cumulative A win rate over chronological samples",
        cumulative,
        "Cumulative win rate",
    )

    rater_labels = list(summary["rater_counts"].keys())
    rater_values = [summary["rater_counts"][r] for r in rater_labels]
    chart_paths["samples_per_rater"] = charts_dir / "samples_per_rater.png"
    _write_bar_chart(
        chart_paths["samples_per_rater"],
        "Samples per rater",
        rater_labels,
        rater_values,
        "Judgments",
    )

    metrics: dict[str, Any] = {
        "suite_name": suite_name,
        "dataset_name": "fake_human_judgments_20_samples",
        "n_samples": summary["n_samples"],
        "holdout_size": max(1, int(round(summary["n_samples"] * 0.2))),
        "demo_dataset_included": demo_dataset_included,
        "win_rate": round(win_point, 4),
        "win_rate_95ci": [round(win_lo, 4), round(win_hi, 4)],
        "significance_vs_50_50": significance,
        "bradley_terry": bradley_terry,
        "heuristic_judge_agreement_rate": agreement_rate,
        "heuristic_judge_cohens_kappa": kappa,
        "inter_rater_reliability": (
            "not computable: every item in this dataset has exactly one rater"
            if single_rating_per_item
            else "computed"
        ),
        "preferences_by_winner": summary["winner_counts"],
        "preferences_by_rater": summary["rater_counts"],
        "reporting_format": ["markdown", "html", "json"],
        "limitations": [
            "Demo dataset uses only two fixed candidate templates repeated across all "
            "20 briefs, so the Bradley-Terry strength gap reflects template style, "
            "not per-brief quality.",
            "One rater per item: no real inter-rater reliability (kappa) is possible "
            "on this dataset; collect >=2 raters/item for that.",
            "heuristic_judge_* metrics come from a deterministic offline text-feature "
            "judge, not a live LLM-graded judge -- see module docstring.",
        ],
    }

    persistence = _persist_run(metrics, chart_paths)
    metrics["database_backend"] = persistence["attempted_backend"]
    metrics["database_write_persisted"] = persistence["persisted"]
    metrics["database_row_count_after_write"] = persistence["row_count_after_write"]
    if persistence["error"]:
        metrics["database_error"] = persistence["error"]

    markdown = f"""# Evaluation Report

- Suite: {suite_name}
- Dataset: {metrics['dataset_name']} (demo dataset included: {demo_dataset_included})
- Samples: {metrics['n_samples']} (holdout size used for reporting: {metrics['holdout_size']})
- Candidate A win rate: {metrics['win_rate']:.3f} (95% bootstrap CI: {metrics['win_rate_95ci'][0]:.3f}-{metrics['win_rate_95ci'][1]:.3f})
- Two-sided binomial test vs 50/50: p = {significance.get('p_value')}, significant at 0.05: {significance.get('significant_at_05')}
- Bradley-Terry P(A beats B): {bradley_terry.get('p_a_beats_b')}
- Heuristic judge vs human agreement: {agreement_rate:.3f} (Cohen's kappa: {kappa})
- Inter-rater reliability: {metrics['inter_rater_reliability']}
- Database backend actually used: {metrics['database_backend']} (write persisted: {metrics['database_write_persisted']})

## Limitations (read before citing these numbers)
{chr(10).join('- ' + item for item in metrics['limitations'])}

## Summary
This report is generated by a statistically grounded pipeline: bootstrap
confidence intervals, a binomial significance test, a Bradley-Terry MLE
fit, and an automated-judge-vs-human agreement check (with Cohen's kappa).
It is intentionally conservative about what the bundled 20-sample demo
dataset can and cannot support -- see the limitations above.
"""
    html = f"""<!doctype html>
<html lang="en">
<head><meta charset="utf-8"><title>{suite_name} report</title></head>
<body>
<h1>Evaluation Report</h1>
<p>Suite: {suite_name}</p>
<p>Samples: {metrics['n_samples']}</p>
<p>Candidate A win rate: {metrics['win_rate']:.3f} (95% CI {metrics['win_rate_95ci'][0]:.3f}-{metrics['win_rate_95ci'][1]:.3f})</p>
<p>Binomial test p-value: {significance.get('p_value')}</p>
<p>Bradley-Terry P(A beats B): {bradley_terry.get('p_a_beats_b')}</p>
<p>Heuristic judge agreement: {agreement_rate:.3f} (kappa: {kappa})</p>
<p>Database backend: {metrics['database_backend']} (persisted: {metrics['database_write_persisted']})</p>
<h2>Limitations</h2>
<ul>
{''.join(f'<li>{item}</li>' for item in metrics['limitations'])}
</ul>
</body>
</html>
"""

    paths["markdown"].write_text(markdown, encoding="utf-8")
    paths["html"].write_text(html, encoding="utf-8")
    (paths["metrics"]).write_text(json.dumps(metrics, indent=2), encoding="utf-8")

    return {
        "summary": summary,
        "metrics": metrics,
        "report_markdown_path": paths["markdown"],
        "report_html_path": paths["html"],
        "metrics_json_path": paths["metrics"],
        "chart_paths": chart_paths,
    }


if __name__ == "__main__":
    from app.preference_store import PreferenceStore

    with PreferenceStore() as store:
        prefs = store.all()
    if not prefs:
        raise SystemExit(
            "No preferences found. Run `python -m training.generate_fake_preferences` first."
        )
    result = run_evaluation_suite(prefs, suite_name="cli-run")
    print(json.dumps(result["metrics"], indent=2))
